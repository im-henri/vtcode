/// Complete JSON-serializable theme definition
#[derive(Serialize, Deserialize, Clone, PartialEq)]
pub(crate) struct ThemeFile {
    /// Provenance is assigned only by the embedded loader, never by theme JSON.
    #[serde(skip)]
    pub builtin: bool,
    #[serde(default)]
    pub is_light: bool,
    #[serde(default)]
    pub high_contrast: bool,
    pub name: String,
    pub config_key: String,
    pub syntax_theme: String,
    pub colors: ThemeColorsFile,
    pub gradients: Option<ThemeGradientsFile>,
    #[serde(default, rename = "tokenColors", skip_serializing_if = "Vec::is_empty")]
    pub token_colors: Vec<serde_json::Value>,
    #[serde(skip)]
    pub textmate_theme: Option<crate::textmate::Theme>,
    #[serde(skip)]
    pub semantic_colors: Option<crate::semantic_theme::SemanticTheme>,
    #[serde(skip)]
    pub semantic_color_rules: serde_json::Map<String, serde_json::Value>,
    #[serde(skip)]
    pub workbench_colors: serde_json::Map<String, serde_json::Value>,
}

