/// Bundled VS Code themes use the same importer as installed themes.
pub(crate) fn load_builtin_themes() -> Vec<ThemeFile> {
    crate::builtin_themes::THEMES.iter().map(|entry| entry.theme().clone()).collect()
}

/// Resolve only the requested built-in. Starting with Dark+ must not parse
/// every other workbench and syntax palette or clone the whole catalog.
pub(crate) fn builtin_theme(key: &str) -> Option<&'static ThemeFile> {
    crate::builtin_themes::THEMES.iter().find(|entry| entry.key == key).map(|entry| entry.theme())
}

/// Load themes explicitly installed into vtcode. Keep filesystem discovery off
/// the render thread; VS Code and other editors' installations are not scanned.
pub(crate) fn load_external_themes() -> Vec<ThemeFile> {
    load_external_themes_from_base(&crate::portable::base_dir())
}

fn load_external_themes_from_base(portable_base: &Path) -> Vec<ThemeFile> {
    let root = portable_base.join(".vtcode/theme-extensions");
    let removed = match crate::theme_catalog::removed(&root) {
        Ok(keys) => keys,
        Err(error) => { log_warn!("{error}"); return Vec::new(); }
    };
    let mut themes = crate::vscode_theme::load_extension_themes_excluding(&root, &removed);
    merge_themes(&mut themes, load_themes_from_dir(&portable_base.join(".vtcode/themes")));
    themes.retain(|theme| !removed.contains(&theme.config_key));
    themes
}

pub(crate) fn load_installed_theme(portable_base: &Path, key: &str) -> Option<ThemeFile> {
    if crate::theme_catalog::removed(&portable_base.join(".vtcode/theme-extensions")).ok()?.contains(key) {
        return None;
    }
    crate::vscode_theme::load_extension_themes_matching(&portable_base.join(".vtcode/theme-extensions"), Some(key))
        .into_iter().next()
        .or_else(|| load_themes_from_dir(&portable_base.join(".vtcode/themes")).into_iter().find(|t| t.config_key == key))
}

/// Load the complete theme registry for tests and explicit synchronous callers.
/// Production construction uses [`load_builtin_themes`] and installs this
/// function's external portion asynchronously.
#[cfg(test)]
pub(crate) fn load_all_themes() -> Vec<ThemeFile> {
    static THEMES: std::sync::OnceLock<Vec<ThemeFile>> = std::sync::OnceLock::new();
    THEMES
        .get_or_init(|| {
            let mut themes = load_builtin_themes();
            merge_themes(&mut themes, load_external_themes());
            themes
        })
        .clone()
}

pub(crate) fn merge_themes(themes: &mut Vec<ThemeFile>, incoming: Vec<ThemeFile>) {
    for theme in incoming {
        if let Some(pos) = themes
            .iter()
            .position(|old| old.config_key == theme.config_key)
        {
            themes[pos] = theme;
        } else {
            themes.push(theme);
        }
    }
}

/// Generate a command ID from a theme config_key (e.g. "dark" -> "theme_dark", "one-dark-pro" -> "theme_one_dark_pro")
pub(crate) fn theme_command_id(config_key: &str) -> String {
    format!("theme_{}", config_key.replace('-', "_"))
}

/// Extract a config key from the command ID generated by `theme_command_id`.
pub(crate) fn config_key_from_command_id(id: &str) -> Option<String> {
    id.strip_prefix("theme_")
        .map(|suffix| suffix.replace('_', "-"))
}

pub(crate) fn hex_to_color(hex: &str) -> Color {
    let hex = hex.trim_start_matches('#');
    if !hex.is_ascii() {
        return Color::Rgb(0, 0, 0);
    }
    match hex.len() {
        3 | 4 => {
            let n = |i| u8::from_str_radix(&hex[i..i + 1], 16).ok().map(|v| v * 17);
            match (n(0), n(1), n(2)) {
                (Some(r), Some(g), Some(b)) => Color::Rgb(r, g, b),
                _ => Color::Rgb(0, 0, 0),
            }
        }
        6 | 8 => {
            let b = |i| u8::from_str_radix(&hex[i..i + 2], 16).ok();
            match (b(0), b(2), b(4)) {
                (Some(r), Some(g), Some(b)) => Color::Rgb(r, g, b),
                _ => Color::Rgb(0, 0, 0),
            }
        }
        _ => Color::Rgb(0, 0, 0),
    }
}

